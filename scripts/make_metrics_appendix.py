"""Generate the complete metrics appendix for PROGRESS.md, from the artifacts.

Usage:  uv run python scripts/make_metrics_appendix.py

WHY THIS IS GENERATED AND NOT WRITTEN
-------------------------------------
PROGRESS.md carries every measured number in the project. Typing forty-odd
figures by hand is how a document drifts: an earlier version of these docs
reported the warehouse as 163 MB in five places long after it had grown to
1.9 GB, because the number was written once and never re-derived.

So the appendix is rendered from the artifact CSVs and the warehouse itself.
Re-run this after any pipeline change and the numbers cannot be stale, because
nothing is transcribed.

Writes between the ANCHOR_START / ANCHOR_END markers in PROGRESS.md, leaving
the rest of the file untouched.
"""

from __future__ import annotations

import polars as pl

from sci.config import REPO_ROOT, settings
from sci.log import get_logger

log = get_logger(__name__)

ART = settings.artifacts_dir
PROGRESS = REPO_ROOT / "PROGRESS.md"

ANCHOR_START = "<!-- METRICS:START - generated by scripts/make_metrics_appendix.py -->"
ANCHOR_END = "<!-- METRICS:END -->"


def _read(name: str) -> pl.DataFrame | None:
    p = ART / f"{name}.csv"
    if not p.exists():
        log.warning("missing artifact: %s", p.name)
        return None
    return pl.read_csv(p, infer_schema_length=10000)


def md_table(df: pl.DataFrame, cols: list[str] | None = None, rename: dict | None = None) -> str:
    """Render a Polars frame as a GitHub markdown table."""
    if df is None or df.height == 0:
        return "_(artifact not available)_\n"
    if cols:
        cols = [c for c in cols if c in df.columns]
        df = df.select(cols)
    headers = [(rename or {}).get(c, c) for c in df.columns]

    def fmt(v) -> str:
        if v is None:
            return ""
        # bool before int: bool subclasses int in Python, so the int branch
        # would render True as "1".
        if isinstance(v, bool):
            return "yes" if v else "no"
        if isinstance(v, float):
            if v != v:  # NaN
                return "—"
            if abs(v) >= 1000:
                return f"{v:,.0f}"
            if abs(v) >= 1:
                return f"{v:,.4f}".rstrip("0").rstrip(".")
            return f"{v:.4f}"
        if isinstance(v, int):
            return f"{v:,}"
        return str(v)

    out = ["| " + " | ".join(headers) + " |"]
    out.append("|" + "|".join("---" for _ in headers) + "|")
    for row in df.iter_rows():
        out.append("| " + " | ".join(fmt(v) for v in row) + " |")
    return "\n".join(out) + "\n"


def section(title: str, body: str, note: str = "") -> str:
    s = f"\n### {title}\n\n"
    if note:
        s += note.rstrip() + "\n\n"
    return s + body


def warehouse_stats() -> str:
    """Live table counts and real file size, straight from DuckDB."""
    from sci.warehouse import connect

    p = settings.duckdb_path
    if not p.exists():
        return "_(warehouse not built)_\n"

    con = connect(read_only=True)
    try:
        rows = con.execute(
            """
            SELECT table_name, estimated_size AS rows
            FROM duckdb_tables() WHERE schema_name = 'core'
            ORDER BY estimated_size DESC
            """
        ).pl()
        size = con.execute("PRAGMA database_size").pl()
    finally:
        con.close()

    blk = int(size["block_size"][0])
    tot, used, free = (int(size[c][0]) for c in ("total_blocks", "used_blocks", "free_blocks"))
    txt = md_table(rows)
    txt += (
        f"\nFile on disk **{tot * blk / 1e9:.2f} GB** "
        f"({tot:,} blocks x {blk / 1024:.0f} KB): "
        f"**{used * blk / 1e9:.2f} GB live**, {free * blk / 1e9:.2f} GB free blocks. "
        "DuckDB does not return pages to the OS after `CREATE OR REPLACE`, so the "
        "file grows across rebuilds without the data growing.\n"
    )
    return txt


def build() -> str:
    parts: list[str] = [
        ANCHOR_START,
        "",
        "## Complete metrics appendix",
        "",
        "**Generated by `scripts/make_metrics_appendix.py` directly from the artifact",
        "CSVs and the warehouse — not transcribed.** Re-run it after any pipeline",
        "change. Everything between the markers is overwritten; edit the generator,",
        "not this block.",
        "",
        "`docs/04-results.md` remains the place for interpretation and caveats; this is",
        "the raw measured record.",
    ]

    # ---- warehouse -------------------------------------------------------
    parts.append(section("Warehouse contents", warehouse_stats()))

    # ---- segmentation ----------------------------------------------------
    parts.append(
        section(
            "ABC x XYZ segmentation",
            md_table(
                _read("abc_xyz_segmentation"),
                [
                    "box",
                    "series",
                    "pct_series",
                    "revenue",
                    "pct_revenue",
                    "avg_cv",
                    "avg_adi",
                    "pct_intermittent_or_lumpy",
                    "policy_hint",
                ],
            ),
        )
    )

    # ---- stockout --------------------------------------------------------
    so = _read("stockout_proxy_detection")
    if so is not None:
        head = so.filter(pl.col("section") == "1_headline")
        seg = so.filter(pl.col("section") == "2_by_segment")
        alpha = so.filter(pl.col("section") == "3_alpha_sensitivity")
        body = "**Headline** — runs | censored days | series | avg len | median | max\n\n"
        body += md_table(
            head,
            [
                "label",
                "metric_a",
                "metric_b",
                "pct_of_panel",
                "metric_c",
                "metric_d",
                "metric_e",
                "metric_f",
            ],
        )
        body += (
            "\n**By ABC / demand class** — series | stockout days | % days | "
            "dormant days | % dormant\n\n"
        )
        body += md_table(
            seg, ["label", "metric_a", "metric_b", "pct_of_panel", "metric_c", "metric_d"]
        )
        body += "\n**Alpha sensitivity** — runs | days | % of panel\n\n"
        body += md_table(alpha, ["label", "metric_a", "metric_b", "pct_of_panel"])
        parts.append(section("Stockout proxy", body))

    # ---- seasonality -----------------------------------------------------
    seas = _read("demand_seasonality_profile")
    if seas is not None:
        body = ""
        for dim, label in [
            ("day_of_week", "Day of week"),
            ("snap", "SNAP days"),
            ("month", "Month"),
            ("event", "Named events"),
        ]:
            sub = seas.filter(pl.col("dimension") == dim)
            if sub.height:
                body += f"\n**{label}**\n\n"
                body += md_table(
                    sub, ["cat_id", "segment", "n_obs", "mean_units", "lift", "pct_vs_baseline"]
                )
        parts.append(section("Seasonality profile", body))

    # ---- price -----------------------------------------------------------
    parts.append(
        section(
            "Price elasticity (naive, NOT causal)",
            md_table(
                _read("price_elasticity_naive"),
                ["cat_id", "dept_id", "n_obs", "elasticity", "r2", "correlation", "reading"],
            ),
        )
    )
    parts.append(
        section(
            "Promotion lift vs matched controls",
            md_table(
                _read("promo_lift_analysis"),
                [
                    "cat_id",
                    "price_state",
                    "discount_band",
                    "matched_cells",
                    "promo_days",
                    "control_days",
                    "lift",
                    "pct_uplift",
                    "median_cell_lift",
                    "avg_discount",
                ],
            ),
        )
    )

    # ---- forecasting -----------------------------------------------------
    parts.append(
        section(
            "Backtest summary (CV folds, ranked)",
            md_table(
                _read("backtest_summary"), ["rank", "model", "wrmsse", "wrmsse_sd", "mase", "folds"]
            ),
        )
    )
    folds = _read("backtest_folds")
    if folds is not None:
        parts.append(
            section(
                "Backtest, per fold",
                md_table(
                    folds.sort(["model", "fold"]),
                    ["model", "fold", "wrmsse", "rmsse_mean", "mase_mean", "n_series_scored"],
                ),
            )
        )
    parts.append(
        section(
            "Error by Syntetos-Boylan class",
            md_table(
                _read("backtest_by_sb_class"),
                ["sb_class", "model", "rmsse_mean", "wrmsse", "n_series"],
            ),
        )
    )
    parts.append(
        section(
            "Error by ABC class",
            md_table(
                _read("backtest_by_abc_class"),
                ["abc_class", "model", "rmsse_mean", "wrmsse", "n_series"],
            ),
        )
    )
    parts.append(
        section(
            "Quantile calibration",
            md_table(
                _read("calibration"),
                ["fold", "method", "quantile", "nominal_coverage", "empirical_coverage", "gap"],
            ),
        )
    )
    seg = _read("calibration_by_segment")
    if seg is not None:
        parts.append(
            section(
                "Calibration by demand class",
                md_table(
                    seg, ["fold", "segment", "quantile", "empirical_coverage", "gap", "n_series"]
                ),
            )
        )
    parts.append(
        section(
            "Pinball loss",
            md_table(_read("pinball"), ["fold", "method", "quantile", "pinball_loss"]),
        )
    )

    fi = _read("feature_importance")
    if fi is not None:
        agg = (
            fi.group_by("feature")
            .agg(pl.col("gain_share").mean())
            .sort("gain_share", descending=True)
        )
        parts.append(
            section(
                "Feature importance (mean gain share across folds)",
                md_table(agg, ["feature", "gain_share"]),
            )
        )

    # ---- decision --------------------------------------------------------
    parts.append(
        section(
            "Counterfactual on the locked test window (d1914-1941)",
            md_table(
                _read("counterfactual"),
                [
                    "policy",
                    "fill_rate",
                    "cycle_service",
                    "avg_on_hand_units",
                    "total_demand_units",
                    "total_unmet_units",
                    "orders_placed",
                    "holding_cost",
                    "stockout_cost",
                    "ordering_cost",
                    "total_cost",
                ],
            ),
        )
    )
    parts.append(
        section(
            "Cost delta, 95% bootstrap CI (resampling series)",
            md_table(
                _read("counterfactual_ci"),
                [
                    "comparison",
                    "cost_a",
                    "cost_b",
                    "delta",
                    "delta_pct",
                    "delta_pct_ci_lo",
                    "delta_pct_ci_hi",
                    "n_boot",
                ],
            ),
        )
    )
    parts.append(
        section(
            "Service-level frontier",
            md_table(
                _read("service_level_frontier"),
                [
                    "policy",
                    "target_service_level",
                    "fill_rate",
                    "cycle_service",
                    "avg_on_hand_units",
                    "avg_safety_stock",
                    "orders_placed",
                    "total_cost",
                ],
            ),
        )
    )

    sens = _read("cost_sensitivity")
    if sens is not None:
        body = (
            f"All {sens.height} cells, sorted. Range "
            f"**{sens['delta_pct'].max():+.2f}% to {sens['delta_pct'].min():+.2f}%**, "
            f"median **{sens['delta_pct'].median():+.2f}%**. "
            f"All negative: **{bool((sens['delta_pct'] < 0).all())}**.\n\n"
        )
        body += md_table(
            sens.sort("delta_pct"),
            [
                "gross_margin",
                "holding_rate",
                "stockout_penalty",
                "baseline_cost",
                "optimized_cost",
                "delta",
                "delta_pct",
                "baseline_fill",
                "optimized_fill",
            ],
        )
        parts.append(section("Cost sensitivity (full factorial)", body))

    parts.append(
        section(
            "Shadow prices",
            md_table(
                _read("shadow_prices"),
                ["constraint", "used", "limit", "utilisation", "shadow_price", "binding"],
            ),
        )
    )

    pol = _read("policy_test")
    if pol is not None:
        summ = (
            pol.group_by(["abc_class", "sb_class"])
            .agg(
                pl.len().alias("series"),
                pl.col("reorder_point").mean().alias("mean_s"),
                pl.col("order_up_to").mean().alias("mean_S"),
                pl.col("safety_stock").mean().alias("mean_safety_stock"),
                pl.col("chosen_service_level").mean().alias("mean_chosen_SL"),
            )
            .sort(["abc_class", "sb_class"])
        )
        body = f"Per-series policy over {pol.height:,} series, summarised by class.\n\n"
        body += md_table(summ)
        lv = (
            pol.group_by("chosen_service_level")
            .agg(pl.len().alias("series"))
            .sort("chosen_service_level")
        )
        body += "\n**Service levels actually chosen by the allocator**\n\n" + md_table(lv)
        parts.append(section("Replenishment policy", body))

    # ---- reconciliation --------------------------------------------------
    parts.append(
        section("Hierarchy levels", md_table(_read("hierarchy_levels"), ["level", "n_nodes"]))
    )
    parts.append(
        section(
            "Reconciliation coherence (adding-up violation)",
            md_table(
                _read("reconciliation_coherence"),
                ["method", "max_abs_violation", "relative_violation"],
            ),
        )
    )

    rec = _read("reconciliation_accuracy")
    lev = _read("hierarchy_levels")
    if rec is not None and lev is not None:
        order = {n: i for i, n in enumerate(lev["level"].to_list())}
        w = rec.pivot(values="rmsse", index=["level", "n_nodes"], on="method")
        w = (
            w.with_columns(
                pl.col("level").replace_strict(order, default=99, return_dtype=pl.Int32).alias("_o")
            )
            .sort("_o")
            .drop("_o")
        )
        parts.append(section("Reconciliation accuracy — RMSSE by level", md_table(w)))

    parts.append("")
    parts.append(ANCHOR_END)
    return "\n".join(parts)


def main() -> None:
    block = build()
    text = PROGRESS.read_text(encoding="utf-8")

    if ANCHOR_START in text and ANCHOR_END in text:
        pre = text[: text.index(ANCHOR_START)]
        post = text[text.index(ANCHOR_END) + len(ANCHOR_END) :]
        text = pre + block + post
    else:
        text = text.rstrip() + "\n\n---\n\n" + block + "\n"

    PROGRESS.write_text(text, encoding="utf-8")
    log.info("wrote %d lines of metrics into %s", len(block.splitlines()), PROGRESS.name)


if __name__ == "__main__":
    main()
